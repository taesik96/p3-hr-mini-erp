from datetime import date, datetime

from erp import rules

POLICY = rules.Policy()        # 조기 출근 미인정, 잔업 30분 이상만 인정


def t(s):
    return datetime.strptime(f"2026-{s}", "%Y-%m-%d %H:%M")


def run(clock_in, clock_out, start, end, brk, types, regular_left=rules.DAY_LIMIT, policy=POLICY):
    """근무 1건을 끝까지 계산해 분류별 '시간'으로 돌려준다"""
    s, e, *_ = rules.recognized_span(t(clock_in), t(clock_out), t(start), t(end), policy)
    segments = rules.minus_break(s, e, t(brk[0]), t(brk[1]))
    pieces = rules.classify(segments, lambda d: types.get(d.day, "소정근로일"), regular_left, {})
    return {k: v / 60 for k, v in rules.summarize(pieces).items()}


def test_주간조_평일_기본형():
    r = run("09-01 07:57", "09-01 19:01", "09-01 08:00", "09-01 19:00", ("09-01 12:00", "09-01 13:00"), {})
    assert (r["기본"], r["연장"], r["야간"]) == (8, 2, 0)


def test_야간조_연장과_야간이_겹침():
    r = run("09-07 19:49", "09-08 07:12", "09-07 20:00", "09-08 07:00", ("09-08 00:00", "09-08 01:00"), {})
    assert (r["기본"], r["연장"], r["야간"], r["연장·야간"]) == (8, 2, 7, 1)


def test_지각하면_연장이_줄어든다():
    r = run("09-10 08:06", "09-10 19:12", "09-10 08:00", "09-10 19:00", ("09-10 12:00", "09-10 13:00"), {})
    assert (r["기본"], round(r["연장"], 2)) == (8, 1.9)


def test_잔업은_30분_이상일_때만_인정():
    short = run("09-02 07:52", "09-02 19:29", "09-02 08:00", "09-02 19:00", ("09-02 12:00", "09-02 13:00"), {})
    long = run("09-02 07:52", "09-02 20:30", "09-02 08:00", "09-02 19:00", ("09-02 12:00", "09-02 13:00"), {})
    assert short["연장"] == 2 and long["연장"] == 3.5


def test_조기_출근_인정으로_바꾸면_반영된다():
    r = run("09-01 07:30", "09-01 19:00", "09-01 08:00", "09-01 19:00", ("09-01 12:00", "09-01 13:00"), {},
            policy=rules.Policy(early_in=True))
    assert (r["기본"], r["연장"]) == (8, 2.5)


def test_휴무일_근로는_주_40시간을_채웠으면_전부_연장():
    r = run("09-12 07:47", "09-12 19:10", "09-12 08:00", "09-12 19:00", ("09-12 12:00", "09-12 13:00"),
            {12: "휴무일"}, regular_left=0)
    assert (r["기본"], r["연장"], r["휴일"]) == (0, 10, 0)


def test_휴무일_근로라도_주_40시간이_안_찼으면_기본부터():
    r = run("09-12 08:00", "09-12 19:00", "09-12 08:00", "09-12 19:00", ("09-12 12:00", "09-12 13:00"),
            {12: "휴무일"}, regular_left=8 * 60)
    assert (r["기본"], r["연장"]) == (8, 2)


def test_주휴일_10시간은_휴일_8시간과_8시간_초과_2시간():
    r = run("09-20 07:48", "09-20 19:01", "09-20 08:00", "09-20 19:00", ("09-20 12:00", "09-20 13:00"), {20: "주휴일"})
    assert (r["기본"], r["연장"], r["휴일"], r["휴일8h초과"]) == (0, 0, 8, 2)


def test_자정_넘어_공휴일로_이어지면_0시부터_휴일():
    r = run("09-23 19:49", "09-24 07:02", "09-23 20:00", "09-24 07:00", ("09-24 00:00", "09-24 01:00"), {24: "공휴일"})
    assert (r["기본"], r["연장"], r["휴일"], r["야간"], r["휴일·야간"]) == (4, 0, 6, 7, 5)


def test_오후_반차는_실근로_4시간():
    r = run("09-23 08:50", "09-23 14:00", "09-23 09:00", "09-23 18:00", ("09-23 12:00", "09-23 13:00"), {})
    assert (r["기본"], r["연장"]) == (4, 0)


def test_주_52시간_초과분():
    assert rules.over_week_max(60 * 60) == 8 * 60
    assert rules.over_week_max(52 * 60) == 0


def test_연차_발생_근속별():
    assert rules.annual_leave_grants(date(2011, 4, 4), date(2026, 9, 30))[0][1] == 22   # 근속 15년
    assert len(rules.annual_leave_grants(date(2026, 3, 2), date(2026, 9, 30))) == 6     # 1년 미만 6개월
    assert rules.annual_leave_grants(date(2025, 11, 3), date(2026, 9, 30), weekly_hours=12) == []
